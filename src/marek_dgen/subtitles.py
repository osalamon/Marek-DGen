from pathlib import Path

from marek_dgen.utils.config import SubtitlesConfig


def _ass_time(seconds: float) -> str:
    """Format seconds as ASS timestamp: h:mm:ss.cc (centiseconds)."""
    cs_total = int(round(max(0.0, float(seconds)) * 100))
    h = cs_total // 360000
    m = (cs_total % 360000) // 6000
    s = (cs_total % 6000) // 100
    cs = cs_total % 100
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def _ass_escape(text: str) -> str:
    """Neutralize ASS override-block braces; convert newlines to \\N."""
    return text.replace("{", "(").replace("}", ")").replace("\n", "\\N")


def generate_ass(
    manifest: list[dict],
    config: SubtitlesConfig,
    output_path: Path,
) -> Path:
    """Generate an .ass subtitle file from manifest entries.

    Translated text is rendered bottom-center ('Translated' style);
    with bilingual=True, the original English is rendered top-center
    ('Original' style) at a smaller font size.
    """
    header = f"""[Script Info]
Title: Dubbed subtitles (generated by marek_dgen)
ScriptType: v4.00+
PlayResX: 288
PlayResY: 288
WrapStyle: 0
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Translated,{config.font_name},{config.font_size},{config.primary_color},&H000000FF,{config.outline_color},&H80000000,0,0,0,0,100,100,0,0,1,2,0,2,20,20,{config.margin_v},1
Style: Original,{config.font_name},{config.secondary_font_size},{config.secondary_color},&H000000FF,{config.outline_color},&H80000000,0,0,0,0,100,100,0,0,1,2,0,8,20,20,{config.margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events: list[str] = []
    for entry in manifest:
        text = (entry.get("text") or "").strip()
        if not text:
            continue
        if entry.get("skipped", False) and not config.include_skipped:
            continue
        start = _ass_time(entry.get("start", 0.0))
        end = _ass_time(entry.get("end", 0.0))
        events.append(
            f"Dialogue: 0,{start},{end},Translated,,0,0,0,,{_ass_escape(text)}\n"
        )
        if config.bilingual:
            original = (entry.get("original_text") or "").strip()
            if original:
                events.append(
                    f"Dialogue: 0,{start},{end},Original,,0,0,0,,{_ass_escape(original)}\n"
                )

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(header)
        f.writelines(events)
    return output_path
